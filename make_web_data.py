"""Pack every result into one small JS file for the interactive page.

Reads only the JSON written by the analysis scripts, so the page can never
drift from the numbers in the figures.
"""
import json
import os

import docking as D

META = {
    "4RMH": {"kind": "holo", "res": 1.42, "bound": "SirReal2 + asetil-lizin peptidi",
             "label": "kendi kristali", "sirreal": True},
    "4RMG": {"kind": "holo", "res": 1.88, "bound": "SirReal2 + NAD+",
             "label": "ikinci kristal formu", "sirreal": True},
    "1J8F": {"kind": "apo", "res": 1.70, "bound": "yok",
             "label": "apo", "sirreal": False},
    "3ZGO": {"kind": "apo", "res": 1.63, "bound": "yok",
             "label": "apo, bağımsız kristal", "sirreal": False},
    "3ZGV": {"kind": "other", "res": 2.27, "bound": "ADP-riboz",
             "label": "ürün bağlı", "sirreal": False},
    "5MAT": {"kind": "induced", "res": 2.07, "bound": "7KJ (tienopirimidinon)",
             "label": "farklı ligandın açtığı cep", "sirreal": False},
    "9FDR": {"kind": "apo-open", "res": 1.25, "bound": "yok",
             "label": "ligandsız ama cep açık", "sirreal": False},
}


def main():
    v1 = json.load(open(os.path.join(D.FIG, "v1_results.json")))["results"]
    sweep = json.load(open(os.path.join(D.FIG, "v2_sweep.json")))["rows"]
    fit = json.load(open(os.path.join(D.FIG, "v2_pocketfit.json")))["rows"]
    v3 = json.load(open(os.path.join(D.FIG, "v3_results.json")))
    v1 = dict(v1) | v3["results"]          # versions 1 and 3 share ligand, box, seeds
    fit = fit + v3["fit"]

    top = {p: {r["seed"]: [round(r["scores"][0], 2), round(r["rmsds"][0], 2)]
               for r in v1[p]["runs"]} for p in v1}
    poses = {p: [[round(rm, 2), round(sc, 2)]
                 for run in v1[p]["runs"]
                 for sc, rm in zip(run["scores"], run["rmsds"])] for p in v1}

    grouped = {}
    for r in sweep:
        grouped.setdefault(r["pdb"], {}).setdefault(str(r["exh"]), []).append(r)
    sw = {p: {e: {"rmsds": [round(x["rmsds"][0], 2) for x in rs],
                  "secs": round(sum(x["secs"] for x in rs) / len(rs), 1),
                  "score": round(sum(x["scores"][0] for x in rs) / len(rs), 2)}
              for e, rs in d.items()} for p, d in grouped.items()}

    ft = {r["pdb"]: {"hard": r["n_hard"], "close": r["n_close"],
                     "min": r["min_dist"], "energy": round(r["score_only"], 1),
                     "nearest": r["nearest"]} for r in fit}

    os.makedirs(os.path.join(D.HERE, "web"), exist_ok=True)
    out = os.path.join(D.HERE, "web", "data.js")
    open(out, "w").write(
        "// Generated by make_web_data.py -- every number comes from the result JSONs.\n"
        f"const META={json.dumps(META, ensure_ascii=False)};\n"
        f"const TOP={json.dumps(top)};\n"
        f"const POSES={json.dumps(poses)};\n"
        f"const SWEEP={json.dumps(sw)};\n"
        f"const FIT={json.dumps(ft)};\n"
        "const SUCCESS=2.0;\n")
    print(f"{out}  {os.path.getsize(out)} bytes")


if __name__ == "__main__":
    main()
